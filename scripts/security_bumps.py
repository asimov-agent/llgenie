#!/usr/bin/env python3
"""The owner of a red scan: the scan's own findings become the floor the pins must reach (#738).

`make security-verdict` says *which* advisories block. `make security-issues` (#716) files them.
Neither can move a pin, so before this module the 8 findings of run 40525155122 red the pipeline
every single run — `certifi`, `filelock` and `urllib3` are **transitive** pins in the generated
`tools/requirements*.txt`, and the remediation bot (#717) only edits a *direct* pin in
`tools/requirements*.in`, so it refused all of them.

This module closes the loop deterministically:

1. **derive the floor** — per package, the lowest fixed version the scanner names that clears every
   advisory it reports for it (the MAXIMUM of the minimums). No version is invented: every value is
   the report's own `fixed`, and a finding without one is never a floor.
2. **write it once** — `tools/security-floors.in`, a pip-compile constraint file that
   `tools/requirements*.in` include with `-c security-floors.in`.
3. **regenerate, never hand-edit** — `make -C tools generate-requirements` and
   `generate-requirements-dev` are the ONE generator of the compiled pins (AGENTS.md), so the
   `.txt` files are rebuilt from `.in` + the floor.
4. **one PR that closes what it fixes** — on `fix/security-floors`, with `Issue: / Fix: / Benefit: /
   Technical:` and a `closes #<n>` line per matched tagged issue. An unsatisfied floor after the
   regeneration opens NO PR and exits non-zero: green or nothing.

Commands (driven by make, never by hand):

    plan    print the floor, the pins it moves, and the issues it would close   make security-bumps-plan
    apply   write the floor, regenerate, gate, push, open/update the PR         make security-bumps
    check   the committed floor is well-formed and satisfied                    make check-security-bumps
"""
from __future__ import annotations

import argparse
import json
import os
import re
import shutil
import subprocess
import sys
from dataclasses import dataclass, field
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO / "scripts"))
import git_identity  # noqa: E402  the ONE source of the commit identity (issue #840)
import security_issues as si  # noqa: E402
import security_scan as ss  # noqa: E402

REPORTS = Path(os.environ.get("SECURITY_REPORTS") or (REPO / "security-reports"))
FLOORS = Path("tools/security-floors.in")
INCLUDE = "-c security-floors.in"
#: The files that own a Python pin as an INPUT. The compiled `.txt` files are regenerated, never edited.
INCLUDING = ("tools/requirements.in", "tools/requirements-dev.in")
COMPILED = ("tools/requirements.txt", "tools/requirements-dev.txt")
GENERATORS = ("generate-requirements", "generate-requirements-dev")
GATES = ("lint", "check-wiring", "check-docs", "check-security-scan", "check-security-bumps")
BRANCH = "fix/security-floors"
HEADER = """\
# GENERATED by `make security-bumps` from the scan reports (issue #738). Do not hand-edit: the next
# daily scan rewrites this file and `make check-security-bumps` reads it.
#
# Every line is the MINIMUM version the scanner says clears the advisories named beside it. The
# `-c security-floors.in` line in requirements*.in makes pip-compile honour it, so the compiled
# requirements.txt is still regenerated, never edited.
"""
LINE = re.compile(r"^(?P<pkg>[A-Za-z0-9_.-]+)>=+(?P<ver>[^#\s]+)\s*(?:#\s*(?P<reason>\S.*))?$")
PINNED = re.compile(r"^(?P<pkg>[A-Za-z0-9_.-]+)==(?P<ver>\S+)\s*$", re.M)


def _part(token: str) -> tuple[int, int, str]:
    return (1, int(token), "") if token.isdigit() else (0, 0, token.lower())


def version_key(text: str) -> tuple:
    """A comparable key for a version string as the scanners write them (`2026.10.18`, `4.2.1`)."""
    return tuple(_part(p) for p in re.split(r"[.\-_+]", str(text)) if p)


@dataclass
class Floor:
    """One package's minimum version, and the advisories that put it there."""

    package: str
    version: str
    current: str
    advisories: list[tuple[str, str]] = field(default_factory=list)

    @property
    def reason(self) -> str:
        names = ", ".join(f"{source} {advisory}" for source, advisory in self.advisories)
        return f"{names}: {self.current or '?'} -> {self.version}"


def floors(items: list[dict], pol: dict | None = None) -> dict[str, Floor]:
    """Per package, the lowest fixed version that clears EVERY advisory reported for it."""
    pol = pol or ss.policy()
    wanted = {str(s).lower() for s in pol.get("issue_severities") or ["critical", "high"]}
    out: dict[str, Floor] = {}
    for item in items:
        if item["severity"] not in wanted:
            continue
        if pol.get("require_fix") and not item["fixed"]:
            continue
        current = str(item.get("current") or "")
        candidates = [v for v in re.split(r"[,\s]+", str(item["fixed"] or ""))
                      if v and version_key(v) > version_key(current)]
        if not candidates:
            continue                      # no fix above what is installed: nothing to floor
        need = min(candidates, key=version_key)
        package = str(item["package"])
        advisory = (str(item["source"]), str(item["id"]))
        held = out.get(package)
        if held is None:
            out[package] = Floor(package, need, current, [advisory])
            continue
        held.advisories.append(advisory)
        if version_key(need) > version_key(held.version):
            held.version = need
    return dict(sorted(out.items()))


def render(fl: dict[str, Floor]) -> str:
    body = "".join(f"{f.package}>={f.version}" + " " * max(1, 24 - len(f"{f.package}>={f.version}"))
                   + f"# {f.reason}\n" for f in fl.values())
    return HEADER + body


def parse_floor_text(text: str) -> tuple[dict[str, str], list[str]]:
    """`{package: version}` and the problems a reader would find in the file."""
    out: dict[str, str] = {}
    problems: list[str] = []
    for number, raw in enumerate(text.splitlines(), start=1):
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        m = LINE.match(line)
        if not m:
            problems.append(f"line {number}: `{line}` is not `package>=version`")
            continue
        if not m.group("reason"):
            problems.append(f"line {number}: `{m.group('pkg')}` states no advisory reason")
        out[m.group("pkg")] = m.group("ver")
    return out, problems


def pinned_versions(root: Path = REPO) -> dict[str, str]:
    """Every `package==version` a compiled requirements file pins."""
    out: dict[str, str] = {}
    for rel in COMPILED:
        path = root / rel
        if not path.is_file():
            continue
        for m in PINNED.finditer(path.read_text(encoding="utf-8")):
            out.setdefault(m.group("pkg").lower(), m.group("ver"))
    return out


def unsatisfied(fl: dict[str, Floor], pinned: dict[str, str]) -> list[tuple[str, str, str]]:
    """The (package, floor, pinned) triples whose compiled pin is below the floor."""
    out = []
    for package, floor in fl.items():
        held = pinned.get(package.lower())
        if held is None:
            continue                       # not pinned here: the constraint simply does not apply
        if version_key(held) < version_key(floor.version):
            out.append((package, floor.version, held))
    return out


def _run_make(args: list[str], root: Path = REPO) -> subprocess.CompletedProcess:
    cmd = ["make", *args]
    print(f"[security-bumps] $ {' '.join(cmd)}")
    return subprocess.run(cmd, cwd=root, capture_output=True, text=True)


def runtime() -> str:
    return os.environ.get("RUNTIME") or ("nerdctl" if shutil.which("nerdctl") else "docker")


def regenerate(root: Path = REPO) -> int:
    """Regenerate BOTH compiled files through the one generator (never by editing a `.txt`)."""
    rc = 0
    for target in GENERATORS:
        res = _run_make(["-C", "tools", target, f"NERDCTL={runtime()}"], root)
        if res.returncode != 0:
            print(f"[security-bumps] {target} failed:\n{res.stdout[-2000:]}{res.stderr[-2000:]}")
            rc = res.returncode
    return rc


def gates(root: Path = REPO) -> tuple[bool, str]:
    output = []
    for name in GATES:
        res = _run_make([name], root)
        output.append(f"$ make {name} -> exit {res.returncode}\n{res.stdout[-2000:]}{res.stderr[-2000:]}")
        if res.returncode != 0:
            return False, "\n".join(output)
    return True, "\n".join(output)


def _gh(args: list[str], repo: str) -> subprocess.CompletedProcess:
    cmd = ["gh", *args, "--repo", repo]
    print(f"[security-bumps] $ {' '.join(cmd)}")
    return subprocess.run(cmd, capture_output=True, text=True)


def matched_issues(fl: dict[str, Floor], repo: str) -> dict[int, Floor]:
    """`{issue number: the floor that closes it}` for the tagged issues this bump fixes."""
    existing = si.existing_issues(repo)
    out: dict[int, Floor] = {}
    for package, floor in fl.items():
        for source, advisory in floor.advisories:
            issue = existing.get(f"{source}:{advisory}:{package}")
            if issue:
                out[int(issue["number"])] = floor
    return dict(sorted(out.items()))


def pr_body(fl: dict[str, Floor], moved: list[tuple[str, str, str]],
            issues: dict[int, Floor], root: Path = REPO) -> str:
    lines = [
        # The author a reviewer sees, before the diff (issue #840).
        git_identity.pr_author_line(),
        "",
        f"Issue: the daily scan reports {sum(len(f.advisories) for f in fl.values())} advisories "
        f"across {len(fl)} package(s) whose fixed version is above the pin this repository compiles "
        f"({', '.join(f.package for f in fl.values())}). Nothing bumped them: they are transitive "
        "pins of the generated `tools/requirements*.txt`.",
        "",
        f"Fix: `{FLOORS}` is written from the reports (the minimum fixed version per package, the "
        "maximum of the minimums), and `" + "`, `".join(INCLUDING) + "` include it with "
        "`-c security-floors.in`. The compiled pins are then REGENERATED by "
        "`make -C tools generate-requirements` / `generate-requirements-dev` — no `.txt` is edited by "
        "hand, and no version is invented.",
        "",
        "Benefit: the next daily scan finds the floor satisfied, so the advisory stops being a "
        "finding instead of redding every push; Renovate (#718) keeps the same pins moving forward "
        "between scans.",
        "",
        "Technical:",
        f"- `{FLOORS}` — {len(fl)} floor line(s).",
        *[f"- `{pkg}`: `{pinned}` -> `{floor}` (floor)" for pkg, floor, pinned in moved],
        f"- Fast gates run before the push: {', '.join('make ' + g for g in GATES)}.",
        f"- The change is one commit on `{BRANCH}`.",
    ]
    if issues:
        lines += ["", "closes " + ", closes ".join(f"#{n}" for n in issues)]
    return "\n".join(lines) + "\n"


def branch_targets(root: Path) -> list[Path]:
    return [root / FLOORS, *[root / rel for rel in COMPILED]]


def apply(repo: str, root: Path = REPO, dry: bool = False, reports: Path | None = None) -> int:
    items = ss.findings(reports or REPORTS)
    fl = floors(items)
    if not fl:
        print("[security-bumps] no advisory names a fix above the installed version — nothing to bump")
        return 0
    text = render(fl)
    pinned = pinned_versions(root)
    moved = unsatisfied(fl, pinned)
    if dry:
        print(text)
        for package, floor, held in moved:
            print(f"[security-bumps] would move {package}: {held} -> {floor}")
        if not moved:
            print("[security-bumps] every floor is already satisfied by the compiled pins")
        print("[security-bumps] DRY: nothing written, nothing regenerated, no PR")
        return 0
    if not moved:
        print("[security-bumps] every floor is already satisfied — no bump PR")
        return 0
    path = root / FLOORS
    before = path.read_text(encoding="utf-8") if path.is_file() else None
    path.write_text(text, encoding="utf-8")
    if regenerate(root) != 0:
        if before is None:
            path.unlink(missing_ok=True)
        else:
            path.write_text(before, encoding="utf-8")
        print("[security-bumps] the regeneration failed — floor reverted, no PR")
        return 1
    still = unsatisfied(fl, pinned_versions(root))
    if still:
        if before is None:
            path.unlink(missing_ok=True)
        else:
            path.write_text(before, encoding="utf-8")
        for package, floor, held in still:
            print(f"[security-bumps] UNSATISFIED {package}: floor {floor}, compiled {held}")
        print("[security-bumps] pip-compile could not reach the floor — reverted, no PR (see #739)")
        return 1
    ok, output = gates(root)
    if not ok:
        if before is None:
            path.unlink(missing_ok=True)
        else:
            path.write_text(before, encoding="utf-8")
        print(f"[security-bumps] gates red after the bump — reverted, no PR\n{output[-4000:]}")
        return 1
    issues = matched_issues(fl, repo)
    branch = BRANCH
    # The identity comes from the ONE seam that sets it (`scripts/git_identity.py`, issue #840).
    git_identity.apply(root)
    steps = [
        ["git", "checkout", "-B", branch],
        ["git", "add", *[str(p.relative_to(root)) for p in branch_targets(root)]],
        ["git", "commit",
         "-m", "fix(security): compile the scan's floors into the pinned requirements",
         "-m", "Issue: the scan reports advisories whose fixed version is above the compiled pin.\n\n"
               "Fix: write `tools/security-floors.in` from the report's own `fixed` versions and "
               "regenerate the compiled requirements (#738).\n\nBenefit: the pins reach the floor the "
               "scan itself names, so the run stops reding on advisories nobody bumped.\n\n"
               "Technical: `make security-bumps` — floors, pip-compile, gates, one PR."],
        # The bot's own PR branch, rewritten every run: the floor file is a standing assertion.
        ["git", "push", "-u", "--force-with-lease", "origin", branch],
    ]
    for step in steps:
        res = subprocess.run(step, cwd=root, capture_output=True, text=True)
        if res.returncode != 0:
            print(f"[security-bumps] `{' '.join(step)}` failed:\n{res.stderr.strip()[-2000:]}")
            return 1
    body = pr_body(fl, moved, issues, root)
    body_file = root / ".git" / "security-bumps-pr-body.md"
    body_file.write_text(body, encoding="utf-8")
    existing = _gh(["pr", "list", "--head", branch, "--state", "open", "--json", "number"], repo)
    number = ""
    if existing.returncode == 0:
        found = json.loads(existing.stdout or "[]")
        number = str(found[0]["number"]) if found else ""
    if number:
        res = _gh(["pr", "edit", number, "--body-file", str(body_file)], repo)
    else:
        res = _gh(["pr", "create", "--head", branch, "--title",
                   "fix(security): compile the scan's floors into the pinned requirements",
                   "--body-file", str(body_file)], repo)
    if res.returncode != 0:
        print(f"[security-bumps] gh failed:\n{res.stderr.strip()[-2000:]}")
        return 1
    print(f"[security-bumps] PR: {res.stdout.strip() or '#' + number}")
    return 0


def check(root: Path = REPO) -> int:
    """The committed floor: well-formed, included, and satisfied by the compiled pins."""
    problems: list[str] = []
    path = root / FLOORS
    if not path.is_file():
        problems.append(f"{FLOORS} is missing — run `make security-bumps`")
        fl: dict[str, str] = {}
    else:
        fl, found = parse_floor_text(path.read_text(encoding="utf-8"))
        problems += [f"{FLOORS}: {item}" for item in found]
    for rel in INCLUDING:
        source = root / rel
        if not source.is_file():
            problems.append(f"{rel} is missing")
            continue
        if INCLUDE not in source.read_text(encoding="utf-8"):
            problems.append(f"{rel} does not carry `{INCLUDE}`: the floor would not be compiled")
    pinned = pinned_versions(root)
    for package, version in fl.items():
        held = pinned.get(package.lower())
        if held is not None and version_key(held) < version_key(version):
            problems.append(f"{package} is pinned at {held}, below its floor {version}")
    if problems:
        print(f"[security-bumps] {len(problems)} problem(s):")
        for item in problems:
            print(f"  - {item}")
        return 1
    named = ", ".join(f"{p}>={v}" for p, v in fl.items()) or "none"
    print(f"[security-bumps] OK: {len(fl)} floor line(s) in {FLOORS}, included by both .in files, "
          f"every compiled pin at or above its floor ({named})")
    return 0


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("command", choices=("plan", "apply", "check"))
    ap.add_argument("--repo", default=os.environ.get("GITHUB_REPOSITORY", ""))
    ap.add_argument("--root", default=str(REPO))
    ap.add_argument("--reports", default=str(REPORTS))
    ap.add_argument("--dry", action="store_true")
    args = ap.parse_args(argv)
    root = Path(args.root)
    if args.command == "check":
        return check(root)
    if args.command == "plan":
        return apply(args.repo, root, dry=True, reports=Path(args.reports))
    if not args.repo:
        raise SystemExit("[security-bumps] set --repo (or $GITHUB_REPOSITORY) to open the bump PR")
    return apply(args.repo, root, dry=args.dry, reports=Path(args.reports))


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
